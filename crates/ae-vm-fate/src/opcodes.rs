    pub fn gas_at_protocol(self, protocol: u32) -> u64 {
        let schedule = self.info().gas_schedule;
        schedule
            .iter()
            .find(|(p, _)| protocol >= *p)
            .unwrap_or_else(|| schedule.last().expect("nonempty gas schedule"))
            .1
    }
