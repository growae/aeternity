#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ApiType {
    KeyBlockHash,
    MicroBlockHash,
    BlockPofHash,
    BlockTxHash,
    BlockStateHash,
    Channel,
    ContractPubkey,
    ContractBytearray,
    ContractStoreKey,
    ContractStoreValue,
    Transaction,
    TxHash,
    OraclePubkey,
    OracleQuery,
    OracleQueryId,
    OracleResponse,
    AccountPubkey,
    AccountSeckey,
    Signature,
    Commitment,
    PeerPubkey,
    Name,
    State,
    Poi,
    StateTrees,
    CallStateTree,
    Bytearray,
}
impl ApiType {
    pub const ALL: [Self; 27] = [
        Self::KeyBlockHash,
        Self::MicroBlockHash,
        Self::BlockPofHash,
        Self::BlockTxHash,
        Self::BlockStateHash,
        Self::Channel,
        Self::ContractPubkey,
        Self::ContractBytearray,
        Self::ContractStoreKey,
        Self::ContractStoreValue,
        Self::Transaction,
        Self::TxHash,
        Self::OraclePubkey,
        Self::OracleQuery,
        Self::OracleQueryId,
        Self::OracleResponse,
        Self::AccountPubkey,
        Self::AccountSeckey,
        Self::Signature,
        Self::Commitment,
        Self::PeerPubkey,
        Self::Name,
        Self::State,
        Self::Poi,
        Self::StateTrees,
        Self::CallStateTree,
        Self::Bytearray,
    ];
    pub const fn prefix(self) -> &'static str {
        match self {
            Self::KeyBlockHash => "kh",
            Self::MicroBlockHash => "mh",
            Self::BlockPofHash => "bf",
            Self::BlockTxHash => "bx",
            Self::BlockStateHash => "bs",
            Self::Channel => "ch",
            Self::ContractPubkey => "ct",
            Self::ContractBytearray => "cb",
            Self::ContractStoreKey => "ck",
            Self::ContractStoreValue => "cv",
            Self::Transaction => "tx",
            Self::TxHash => "th",
            Self::OraclePubkey => "ok",
            Self::OracleQuery => "ov",
            Self::OracleQueryId => "oq",
            Self::OracleResponse => "or",
            Self::AccountPubkey => "ak",
            Self::AccountSeckey => "sk",
            Self::Signature => "sg",
            Self::Commitment => "cm",
            Self::PeerPubkey => "pp",
            Self::Name => "nm",
            Self::State => "st",
            Self::Poi => "pi",
            Self::StateTrees => "ss",
            Self::CallStateTree => "cs",
            Self::Bytearray => "ba",
        }
    }
    pub fn from_prefix(prefix: &str) -> Option<Self> {
        match prefix {
            "kh" => Some(Self::KeyBlockHash),
            "mh" => Some(Self::MicroBlockHash),
            "bf" => Some(Self::BlockPofHash),
            "bx" => Some(Self::BlockTxHash),
            "bs" => Some(Self::BlockStateHash),
            "ch" => Some(Self::Channel),
            "ct" => Some(Self::ContractPubkey),
            "cb" => Some(Self::ContractBytearray),
            "ck" => Some(Self::ContractStoreKey),
            "cv" => Some(Self::ContractStoreValue),
            "tx" => Some(Self::Transaction),
            "th" => Some(Self::TxHash),
            "ok" => Some(Self::OraclePubkey),
            "ov" => Some(Self::OracleQuery),
            "oq" => Some(Self::OracleQueryId),
            "or" => Some(Self::OracleResponse),
            "ak" => Some(Self::AccountPubkey),
            "sk" => Some(Self::AccountSeckey),
            "sg" => Some(Self::Signature),
            "cm" => Some(Self::Commitment),
            "pp" => Some(Self::PeerPubkey),
            "nm" => Some(Self::Name),
            "st" => Some(Self::State),
            "pi" => Some(Self::Poi),
            "ss" => Some(Self::StateTrees),
            "cs" => Some(Self::CallStateTree),
            "ba" => Some(Self::Bytearray),
            _ => None,
        }
    }
    pub const fn payload_size(self) -> Option<usize> {
        match self {
            Self::KeyBlockHash => Some(32),
            Self::MicroBlockHash => Some(32),
            Self::BlockPofHash => Some(32),
            Self::BlockTxHash => Some(32),
            Self::BlockStateHash => Some(32),
            Self::Channel => Some(32),
            Self::ContractPubkey => Some(32),
            Self::ContractBytearray => None,
            Self::ContractStoreKey => None,
            Self::ContractStoreValue => None,
            Self::Transaction => None,
            Self::TxHash => Some(32),
            Self::OraclePubkey => Some(32),
            Self::OracleQuery => None,
            Self::OracleQueryId => Some(32),
            Self::OracleResponse => None,
            Self::AccountPubkey => Some(32),
            Self::AccountSeckey => Some(32),
            Self::Signature => Some(64),
            Self::Commitment => Some(32),
            Self::PeerPubkey => Some(32),
            Self::Name => None,
            Self::State => Some(32),
            Self::Poi => None,
            Self::StateTrees => None,
            Self::CallStateTree => None,
            Self::Bytearray => None,
        }
    }
    pub const fn is_base64(self) -> bool {
        match self {
            Self::KeyBlockHash => false,
            Self::MicroBlockHash => false,
            Self::BlockPofHash => false,
            Self::BlockTxHash => false,
            Self::BlockStateHash => false,
            Self::Channel => false,
            Self::ContractPubkey => false,
            Self::ContractBytearray => true,
            Self::ContractStoreKey => true,
            Self::ContractStoreValue => true,
            Self::Transaction => true,
            Self::TxHash => false,
            Self::OraclePubkey => false,
            Self::OracleQuery => true,
            Self::OracleQueryId => false,
            Self::OracleResponse => true,
            Self::AccountPubkey => false,
            Self::AccountSeckey => false,
            Self::Signature => false,
            Self::Commitment => false,
            Self::PeerPubkey => false,
            Self::Name => false,
            Self::State => true,
            Self::Poi => true,
            Self::StateTrees => true,
            Self::CallStateTree => true,
            Self::Bytearray => true,
        }
    }
}
