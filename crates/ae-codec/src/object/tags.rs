#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn all_pinned_tags_are_unique_and_reversible() {
        let mut tags = std::collections::BTreeSet::new();
        for t in ObjectTag::ALL {
            assert!(tags.insert(t as u64));
            assert_eq!(ObjectTag::try_from(t as u64), Ok(t));
        }
        assert_eq!(ObjectTag::try_from(0), Err(()));
    }
}
